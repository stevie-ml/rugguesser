export function isNewWorldRug(rug: {
  provenance: string;
  culture: string;
  title: string;
}): boolean {
  const text =
    `${rug.provenance} ${rug.culture} ${rug.title}`.toLowerCase();
  return NEW_WORLD_TERMS.some((term) => text.includes(term));
}
